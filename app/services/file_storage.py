"""Local file storage helpers.

All paths are generated by the server. Clients never supply file names or
paths. The database stores paths relative to the certificates directory, so
swapping this module for S3 later would not change the rest of the code.
"""
from pathlib import Path


def build_relative_path(job_id: int, certificate_code: str) -> Path:
    """e.g. job_1/CERT-000001.pdf (both parts are server-generated)."""
    return Path(f"job_{job_id}") / f"{certificate_code}.pdf"


def resolve_safe_path(base_dir: Path, relative_path: str | None) -> Path | None:
    """Return the absolute path only if it stays inside base_dir, else None."""
    if not relative_path:
        return None
    base = base_dir.resolve()
    candidate = (base / relative_path).resolve()
    if not candidate.is_relative_to(base):
        return None
    return candidate
